# Gold-set and source status report -> reports/goldset/README.md + figures/.
#
# Reads repository files only (no network). Deterministic: the header shows the
# last commit of the input files, not the time of the run, so re-running on
# unchanged inputs gives no diff. Never reads the local full-text folder (only its manifest).
#
# Usage: Rscript scripts/report_goldset.R

for (f in c("R/validate.R", "R/knowledge.R", "R/goldset.R", "R/db.R", "R/report.R")) source(f)

OUT_DIR <- "reports/goldset"
FIG_DIR <- file.path(OUT_DIR, "figures")
dir.create(FIG_DIR, showWarnings = FALSE, recursive = TRUE)
FIGS <- character()
fig <- function(name) { FIGS <<- c(FIGS, name); file.path(FIG_DIR, name) }
fig_md <- function(name, alt) sprintf("![%s](figures/%s)", alt, name)

# ---- inputs ----------------------------------------------------------------------

scope <- yaml::read_yaml("config/scope.yaml")
gs <- read_goldset()
bad <- validate_goldset(gs)
if (nrow(bad)) stop("goldset.csv does not validate; run scripts/goldset_import.R checks first")

manifest <- readr::read_csv("goldset/fulltext_manifest.csv",
                            col_types = readr::cols(.default = readr::col_character()))
baseline_file <- latest_file("reports", paste0("^gbif_baseline_", scope$name, "_.*\\.tsv$"))
comparison_file <- latest_file("reports", "^gbif_baseline_comparison_.*\\.tsv$")
groups_file <- latest_file("reports", "^gbif_survey_groups_.*\\.tsv$")
reference_file <- latest_file("goldset/reference", "\\.tsv$")
baseline <- read_tsv_chr(baseline_file)
comparison <- read_tsv_chr(comparison_file)
groups <- read_tsv_chr(groups_file)
agg_keys <- aggregator_dataset_keys()

inputs <- c("goldset/goldset.csv", "goldset/fulltext_manifest.csv", "config/scope.yaml",
            baseline_file, comparison_file, groups_file, reference_file,
            "logs/queries.jsonl", "knowledge")
state <- git_input_state(inputs)

# ---- 1. header -------------------------------------------------------------------

inc <- table(factor(gs$include, levels = c("yes", "candidate", "no")))
header <- c(
  "# Gold set and sources: status report",
  "",
  "_Generated by `scripts/report_goldset.R`. Do not edit by hand._",
  "",
  md_table(data.frame(
    item = c("Inputs as of", "Input commit", "Scope", "goldset.csv SHA-256",
             "Rows (include: yes / candidate / no)", "Rows with a local full text"),
    value = c(state$date,
              paste0("`", state$commit, "`", if (state$dirty) " + uncommitted changes" else ""),
              sprintf("`%s` (%s, %s)", scope$name, scope$taxa$label, scope$region$label),
              paste0("`", short_sha256("goldset/goldset.csv"), "`"),
              sprintf("%d (%d / %d / %d)", nrow(gs), inc[["yes"]], inc[["candidate"]], inc[["no"]]),
              sprintf("%d (from `goldset/fulltext_manifest.csv`)",
                      fulltext_row_count(manifest, gs$survey_ref)))),
    align = c("l", "l")),
  "")
if (inc[["yes"]] == 0) {
  header <- c(header,
    "> [!WARNING]",
    "> **Everything in this report is provisional.** No gold-set row has `include = yes`:",
    "> all rows are unverified candidates or exclusions until Anders has checked them.",
    "")
}
header <- c(header,
  "Contents: [Gold set](#gold-set-at-a-glance) · [Timeline](#timeline) ·",
  "[Sources](#source-comparison) · [GBIF baseline](#gbif-baseline) ·",
  "[Benchmarks](#pipeline-benchmarks) · [Open items](#open-items) · [Figures](#figures)",
  "")

# ---- 2. gold set at a glance -----------------------------------------------------

gs$institution_group <- institution_group(gs$institution)
status_f <- factor(gs$expected_status, levels = STATUS_LEVELS)
xt <- as.data.frame.matrix(table(status_f, gs$found_via))
xt <- xt[rowSums(xt) > 0, , drop = FALSE]
xt <- cbind(expected_status = rownames(xt), xt, total = rowSums(xt))

save_png(plot_status_by_found_via(gs), fig("status_by_found_via.png"), 7, 4)

glance <- c(
  "## Gold set at a glance",
  "",
  "Rows by `expected_status` and `found_via` (all `include` values).",
  "",
  md_table(xt),
  "",
  fig_md("status_by_found_via.png", "Stacked bars: gold-set rows per found_via, coloured by expected_status"),
  "",
  "**Borderline**",
  "",
  md_table(as.data.frame(table(is_borderline = gs$is_borderline), responseName = "rows")),
  "",
  "**Institution type.** Rule (`institution_group()` in `R/report.R`): drop",
  "\"(oppdragsgiver …)\", then the first match of NTNU, NINA, NIVA, consultancy",
  "(named firms or an AS/AB legal form), otherwise other.",
  "",
  md_table(as.data.frame(table(institution_type = gs$institution_group), responseName = "rows")),
  "")

# ---- 3. timeline -----------------------------------------------------------------

iv <- parse_period(gs$period)
unparsed <- unique(iv$id[!iv$ok])
n_tl <- length(unique(iv$id[iv$ok]))
save_png(plot_timeline(gs, iv), fig("timeline.png"), 8, 1.6 + 0.16 * n_tl)

timeline <- c(
  "## Timeline",
  "",
  "One bar per survey over its period (a single year spans that year). Colour is",
  "`expected_status`; panels are institution types. Periods marked `?` are drawn",
  "as dashed outlines.",
  "",
  fig_md("timeline.png", "Timeline of gold-set surveys by institution type"),
  "",
  if (length(unparsed)) c(
    "**Periods that could not be parsed** (not shown in the figure):",
    "",
    md_table(data.frame(survey_ref = gs$survey_ref[unparsed], period = gs$period[unparsed])))
  else "All periods were parsed.",
  "")

# ---- 4. source comparison --------------------------------------------------------

m <- source_matrix(gs, baseline$datasetKey, agg_keys, groups)
coverage <- source_coverage(m)
flags <- matrix_flags(m)
save_png(plot_source_matrix(m), fig("source_matrix.png"), 7, 1.6 + 0.15 * nrow(m))
save_png(plot_source_overlap(m), fig("source_overlap.png"), 7, 4.5)

unres <- extract_dataset_keys(gs$where_data_are, baseline$datasetKey)
unres_df <- data.frame(survey_ref = rep(gs$survey_ref, vapply(unres, function(u) length(u$unresolved), 1L)),
                       key_prefix = unlist(lapply(unres, `[[`, "unresolved")))

m_tab <- m[order(factor(m$expected_status, levels = STATUS_LEVELS), m$survey_ref), ]
names(m_tab)[match(names(EVIDENCE_COLUMNS), names(m_tab))] <- unname(EVIDENCE_COLUMNS)
comb <- source_combinations(m)
comb$combination <- vapply(strsplit(comb$combination, "+", fixed = TRUE), function(s)
  paste(ifelse(s %in% names(EVIDENCE_COLUMNS), EVIDENCE_COLUMNS[s], s), collapse = " + "), "")

sources <- c(
  "## Source comparison",
  "",
  "Each cell says whether the gold set records evidence that the survey can be",
  "found in that source: `yes` (identifier or exact match), `no` (the gold set",
  "asserts absence), `unknown` (cannot be decided from the recorded fields; never",
  "a guess). Rules, one tested function each in `R/report.R`:",
  "",
  md_table(data.frame(
    column = unname(EVIDENCE_COLUMNS),
    yes = c("`where_data_are` cites a non-aggregator datasetKey (full UUID, or an 8-hex prefix matching exactly one dataset in the baseline), or quotes `datasetName \"…\"` equal to a non-aggregator group in `gbif_survey_groups`",
            "`where_data_are` cites the Vannmiljø datasetKey (from `knowledge/aggregators/vannmiljo.md`), or a vannlokalitetkode found in a Vannmiljø group in a year inside the parsed period",
            "`documents` contains `nva:<id>`",
            "`documents` contains a DOI (`10.xxxx/…`) or a handle (`hdl:`, `handle:`, `hdl.handle.net`)",
            "`documents` is non-empty and has no NVA id, DOI or handle (an ISBN is not a repository id)",
            "`documents` is empty"),
    no = c("no evidence, and `expected_status` is open_elsewhere, exists_not_available, unidentified or not_applicable",
           "same as GBIF dataset", "never", "never", "otherwise", "otherwise"),
    unknown = c("otherwise; also when evidence and such a status conflict (listed under Flags)",
                "same as GBIF dataset", "otherwise", "otherwise", "never", "never")),
    align = "l"),
  "",
  fig_md("source_matrix.png", "Tile matrix of surveys by source evidence, sorted by expected_status"),
  "",
  "### What the matrix says",
  "",
  matrix_summary_text(m, coverage, flags),
  "",
  "### Coverage per source",
  "",
  md_table(stats::setNames(coverage, c("source", "rows covered", "rows only this source", "rows unknown"))),
  "",
  fig_md("source_overlap.png", "UpSet-style bars: gold-set rows per combination of sources"),
  "",
  md_table(stats::setNames(comb, c("sources with yes", "rows"))),
  "",
  "### Flags",
  "",
  if (nrow(flags)) md_table(flags) else "No flags.",
  "",
  if (nrow(unres_df)) c(
    "Dataset-key prefixes in `where_data_are` that do not match a dataset in the",
    "scope baseline (not counted as evidence):", "", md_table(unres_df), "") else character(),
  "<details><summary>Full matrix (table)</summary>",
  "",
  md_table(m_tab),
  "",
  "</details>",
  "")

# ---- 5. GBIF baseline ------------------------------------------------------------

save_png(plot_gbif_datasets(baseline), fig("gbif_records_per_dataset.png"), 8, 4.2)
top3 <- baseline[order(-as.numeric(baseline$n), baseline$datasetKey), ][1:min(3, nrow(baseline)), ]
years <- gbif_year_counts("logs/queries.jsonl", scope, top3$datasetKey)
titles <- stats::setNames(top3$title, top3$datasetKey)
year_block <- if (is.null(years)) {
  c("Records per year cannot be drawn: the raw year-facet responses referenced in",
    "`logs/queries.jsonl` are not present in `data/raw/` on this machine. Run",
    "`scripts/02_gbif_baseline.R` to fetch them.",
    "", md_table(data.frame(missing_file = attr(years, "missing"))))
} else {
  save_png(plot_gbif_years(years, titles), fig("gbif_records_per_year_top3.png"), 8, 6)
  chk <- stats::aggregate(n ~ datasetKey, data = years, FUN = sum)
  chk$title <- titles[chk$datasetKey]
  chk$n_baseline <- as.integer(top3$n[match(chk$datasetKey, top3$datasetKey)])
  chk <- chk[match(top3$datasetKey, chk$datasetKey), c("title", "n_baseline", "n")]
  names(chk) <- c("dataset", "records (baseline)", "records with a year")
  c(fig_md("gbif_records_per_year_top3.png", "Records per year for the three largest datasets"),
    "", "Year counts are the GBIF year facets logged in `logs/queries.jsonl` (raw",
    "responses in local `data/raw/`), summed over the scope taxa.", "", md_table(chk))
}
cmp <- data.frame(dataset = comparison$title, n_reference = as.integer(comparison$n_ref),
                  n_now = as.integer(comparison$n_now), diff = comparison$diff,
                  years_reference = comparison$years_ref, years_now = comparison$years_now)

gbif <- c(
  "## GBIF baseline",
  "",
  sprintf("Scope records per dataset (`%s`), %d datasets, %s records.",
          basename(baseline_file), nrow(baseline), fmt_int(sum(as.numeric(baseline$n)))),
  "",
  fig_md("gbif_records_per_dataset.png", "Records per GBIF dataset, log scale"),
  "",
  year_block,
  "",
  sprintf("Comparison with the reference table (`%s`, `%s`); `diff` = now − reference.",
          basename(comparison_file), basename(reference_file)),
  "",
  md_table(cmp),
  "")

# ---- 6. pipeline benchmarks ------------------------------------------------------

scope_sources <- names(scope$sources)
active <- scope_sources[vapply(scope$sources, function(s) isTRUE(s) ||
                                 (is.list(s) && any(unlist(s) %in% TRUE)), logical(1))]
runs <- if (file.exists(DEFAULT_DB_PATH)) {
  con <- db_connect(DEFAULT_DB_PATH)
  r <- if ("run_log" %in% db_tables(con)) db_search_runs(con) else data.frame()
  db_disconnect(con)
  r
} else data.frame()

bench_note <- c(
  "How the numbers are computed (`benchmark_recall()` in `R/report.R`, tested in",
  "`tests/testthat/test-report.R`):",
  "",
  "- **n_eligible**: gold-set rows with `include = yes`, `expected_status` not",
  "  `not_applicable`, and `found_via` not mapped to the source",
  sprintf("  (%s). Recall is never measured on rows the source itself supplied.",
          paste(sprintf("`%s` → %s", names(FOUND_VIA_SOURCE), FOUND_VIA_SOURCE), collapse = ", ")),
  "- **n_found**: eligible rows matched to a document or dataset the run retrieved.",
  "- **recall** = n_found / n_eligible.",
  "- **n_screened**: records in a hand-checked random sample of the run's output;",
  "  **precision** = relevant records in the sample / n_screened.")
bench_tab <- if (!nrow(runs)) {
  data.frame(source = scope_sources, run = "not run", n_eligible = "", n_found = "",
             recall = "", n_screened = "", precision = "")
} else {
  # Runs are logged, but matching retrieved records to gold-set rows is not
  # implemented yet: show the runs, leave the numbers empty and say so.
  data.frame(source = runs$step, run = paste0("run_log ", runs$run_id, " (", runs$started_at, ")"),
             n_eligible = "", n_found = "not matched yet", recall = "", n_screened = "",
             precision = "")
}

bench <- c(
  "## Pipeline benchmarks",
  "",
  if (!nrow(runs)) sprintf(paste(
    "**Not run.** The register has no search runs (`run_log.kind = 'search'`).",
    "Sources active in `config/scope.yaml`: %s; the GBIF baseline is not a",
    "literature search and is not benchmarked here."),
    paste0("`", active, "`", collapse = ", "))
  else "Search runs are logged, but gold-set matching is not implemented yet.",
  "",
  md_table(bench_tab[BENCHMARK_COLUMNS], align = c("l", "l", "r", "r", "r", "r", "r")),
  "",
  bench_note,
  "",
  "Eligible rows per source today, for reference:",
  "",
  md_table(benchmark_eligible(gs, scope_sources)),
  "")

# ---- 7. open items ---------------------------------------------------------------

open <- gs[gs$expected_status == "todo" | gs$is_borderline == "yes", ]
open <- open[order(open$expected_status != "todo", open$survey_ref), ]
open_tab <- data.frame(survey_ref = open$survey_ref,
                       reason = ifelse(open$expected_status == "todo" & open$is_borderline == "yes",
                                       "todo, borderline",
                                       ifelse(open$expected_status == "todo", "todo", "borderline")),
                       include = open$include,
                       notes = truncate_text(open$notes, 110))
open_md <- c(
  "## Open items",
  "",
  sprintf("Rows with `expected_status = todo` (%d) or `is_borderline = yes` (%d). Notes are truncated.",
          sum(gs$expected_status == "todo"), sum(gs$is_borderline == "yes")),
  "",
  md_table(open_tab),
  "")

# ---- figures list and write ------------------------------------------------------

figs <- FIGS
fig_list <- c("## Figures", "", paste0("- [`figures/", figs, "`](figures/", figs, ")"), "")

writeLines(c(header, glance, timeline, sources, gbif, bench, open_md, fig_list),
           file.path(OUT_DIR, "README.md"), useBytes = TRUE)
message("Wrote ", file.path(OUT_DIR, "README.md"), " and ", length(figs), " figures")
